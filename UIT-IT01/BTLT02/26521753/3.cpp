#include <bits/stdc++.h>

using namespace std;

signed main() {
  double a, b;
  cout << "======= Tinh chu vi/ dien tich hinh chu nhat =======\n";
  cout << "\n==================== INPUT =========================\n";
  cout << "Nhap vao canh a: ";
  cin >> a;
  cout << "Nhap vao canh b: ";
  cin >> b;
  cout << "\n==================== OUTPUT ========================\n";
  cout << "Chu vi cua hinh chu nhat: " << (a + b) * 2.0 << "\n";
  cout << "Dien tich cua hinh chu nhat: " << (a * b) << "\n";
}
